def paginate_offer(text: str = PUBLIC_OFFER_TEXT, *, limit: int = MAX_OFFER_PAGE_CHARS) -> tuple[str, ...]:
    paragraphs = [part.strip() for part in text.split("\n\n") if part.strip()]
    pages: list[str] = []
    current: list[str] = []
    current_len = 0
    for paragraph in paragraphs:
        extra = len(paragraph) + (2 if current else 0)
        if current and current_len + extra > limit:
            pages.append("\n\n".join(current))
            current = []
            current_len = 0
        if len(paragraph) > limit:
            # Legal paragraphs are intentionally kept short; fail loudly on regressions.
            raise ValueError(f"Offer paragraph exceeds Telegram page limit: {len(paragraph)}")
        current.append(paragraph)
        current_len += len(paragraph) + (2 if len(current) > 1 else 0)
    if current:
        pages.append("\n\n".join(current))
    return tuple(pages)


